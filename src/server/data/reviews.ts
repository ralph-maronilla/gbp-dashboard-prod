import "server-only";
import type { Prisma } from "@/generated/prisma/client";
import { formatDateTime, splitName, startOfDayInZone } from "@/lib/export/reviews-csv";
import type { ReviewFilter, ReviewRow, ReviewSort } from "@/lib/schemas/extract";
import { UNASSIGNED } from "@/lib/schemas/insights";
import { PH_REGIONS, regionName } from "@/lib/ph-regions";

/**
 * The reviews a caller asked for, limited to what they may see. Used by the reviews table and the CSV export so both
 * always agree. `visibleIds` null = admin (everything); non-admins never see inactive locations (same as the dashboard).
 * RLS applies on top because callers run this through ctx.db.
 */
export function buildReviewWhere(filter: ReviewFilter, visibleIds: string[] | null, timeZone: string): Prisma.reviewsWhereInput {
  const regionAnd: Prisma.locationsWhereInput[] = [];
  if (filter.region) regionAnd.push({ region: filter.region === UNASSIGNED ? null : filter.region });
  if (filter.island) regionAnd.push({ region: { in: PH_REGIONS.filter((r) => r.island === filter.island).map((r) => r.code) } });
  const location: Prisma.locationsWhereInput = {
    ...(visibleIds === null ? {} : { is_active: true }),
    ...(filter.group_id ? { group_members: { some: { group_id: filter.group_id } } } : {}),
    // Same matching as the Dashboard's Type filter: ignores letter case, UNASSIGNED = no type set.
    ...(filter.location_type
      ? { location_type: filter.location_type === UNASSIGNED ? null : { equals: filter.location_type, mode: "insensitive" as const } }
      : {}),
    ...(regionAnd.length > 0 ? { AND: regionAnd } : {}),
  };

  const and: Prisma.reviewsWhereInput[] = [];
  if (filter.replied) and.push({ reply_comment: filter.replied === "yes" ? { not: null } : null });
  // Extraction stores a missing comment as null (text is trimmed), so "rating only" = no comment.
  if (filter.has_comment) and.push({ comment: filter.has_comment === "yes" ? { not: null } : null });
  // reply_hours is generated by Postgres from reply_time - create_time (migration 0020).
  if (filter.reply_time === "day") and.push({ reply_hours: { lte: 24 } });
  if (filter.reply_time === "week") and.push({ reply_hours: { gt: 24, lte: 24 * 7 } });
  if (filter.reply_time === "slow") and.push({ reply_hours: { gt: 24 * 7 } });
  if (filter.q) {
    const contains = { contains: filter.q, mode: "insensitive" as const };
    const fields: Prisma.reviewsWhereInput[] = [];
    if (filter.search_in === "all" || filter.search_in === "comment") fields.push({ comment: contains });
    if (filter.search_in === "all" || filter.search_in === "reply") fields.push({ reply_comment: contains });
    if (filter.search_in === "all" || filter.search_in === "name") fields.push({ reviewer_name: contains });
    and.push({ OR: fields });
  }
  const ids =
    visibleIds === null
      ? filter.location_id
        ? [filter.location_id]
        : null
      : filter.location_id
        ? visibleIds.filter((id) => id === filter.location_id)
        : visibleIds;

  return {
    ...(ids ? { location_id: { in: ids } } : {}),
    location,
    ...(filter.rating ? { rating: { in: filter.rating } } : {}),
    ...(filter.from || filter.to
      ? {
          create_time: {
            ...(filter.from ? { gte: startOfDayInZone(filter.from, timeZone) } : {}),
            // `to` is inclusive: everything before the start of the next day.
            ...(filter.to ? { lt: new Date(startOfDayInZone(filter.to, timeZone).getTime() + 86_400_000) } : {}),
          },
        }
      : {}),
    ...(and.length > 0 ? { AND: and } : {}),
  };
}

export const reviewSheetSelect = {
  id: true,
  reference_no: true,
  create_time: true,
  reviewer_name: true,
  reviewer_url: true,
  rating: true,
  comment: true,
  reply_comment: true,
  reply_time: true,
  location_id: true,
  location: {
    select: {
      name: true,
      address: true,
      branch_prefix: true,
      location_type: true,
      region: true,
      group_members: { select: { group: { select: { name: true } } }, orderBy: { group: { name: "asc" } } },
    },
  },
} satisfies Prisma.reviewsSelect;

type Dir = "asc" | "desc";
const nullsLast = (sort: Dir) => ({ sort, nulls: "last" as const });

/**
 * Sort order for the reviews table. Every order ends with the review id so paging is stable (no row appears on two pages
 * or none when values tie), and ties fall back to newest first. Empty values (no comment, no branch prefix) go last in
 * both directions so a click never fills the first page with blanks.
 */
export function reviewOrderBy(sort: ReviewSort, order: Dir): Prisma.reviewsOrderByWithRelationInput[] {
  const newestFirst: Prisma.reviewsOrderByWithRelationInput[] = [{ create_time: "desc" }, { id: "desc" }];
  switch (sort) {
    case "rating":
      return [{ rating: order }, ...newestFirst];
    case "reference":
      return [{ reference_no: order }, { id: order }];
    case "name":
      return [{ reviewer_name: nullsLast(order) }, ...newestFirst];
    case "comment":
      return [{ comment: nullsLast(order) }, ...newestFirst];
    case "branch": // the table shows the branch prefix, or the location name when none is set
      return [{ location: { branch_prefix: nullsLast(order) } }, { location: { name: order } }, ...newestFirst];
    case "type": // locations with no type go last
      return [{ location: { location_type: nullsLast(order) } }, { location: { name: order } }, ...newestFirst];
    case "location": // the table shows the address, or the location name when none is set
      return [{ location: { address: nullsLast(order) } }, { location: { name: order } }, ...newestFirst];
    default:
      return [{ create_time: order }, { id: order }];
  }
}

type SheetReview = Prisma.reviewsGetPayload<{ select: typeof reviewSheetSelect }>;

/** A stored review as one table row (and the source of every CSV cell), dates in `timeZone`. */
export function toReviewRow(r: SheetReview, timeZone: string): ReviewRow {
  const { first, middle, last } = splitName(r.reviewer_name);
  return {
    id: r.id,
    reference: String(r.reference_no),
    datetime: formatDateTime(r.create_time, timeZone),
    created_at: r.create_time.toISOString(),
    branch: r.location.branch_prefix ?? r.location.name,
    first_name: first,
    middle_name: middle,
    reviewer_url: r.reviewer_url,
    last_name: last,
    location: r.location.address ?? r.location.name,
    location_id: r.location_id,
    location_type: r.location.location_type,
    client: r.location.group_members.map((m) => m.group.name).join(", "),
    region: regionName(r.location.region),
    rating: r.rating,
    comment: r.comment,
    reply: r.reply_comment,
    reply_date: r.reply_comment && r.reply_time ? formatDateTime(r.reply_time, timeZone) : null,
  };
}
